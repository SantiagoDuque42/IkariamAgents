// Generate strategist/engine/costs.js from IkaEasy's in-game Help scrape (js/helper/db/buildings.js).
// The source file is parsed as data (JSON after stripping `export default`), never executed.
// Usage: node tools/gen-costs.mjs <path-to-ikaeasy>/js/helper/db/buildings.js > strategist/engine/costs.js
import { readFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/gen-costs.mjs <ikaeasy buildings.js>'); process.exit(1); }
const text = readFileSync(src, 'utf8').replace(/^\s*export\s+default\s*/, '').replace(/;\s*$/, '');
const db = JSON.parse(text);
const RES = ['wood', 'wine', 'marble', 'glass', 'sulfur'];
const out = {};
for (const [b, rows] of Object.entries(db)) out[b] = rows.map(r => RES.map(k => Number(r[k]) || 0));
process.stdout.write('// Base building costs per level, index = level-1, order [wood,wine,marble,glass,sulfur]\n' +
  '// Generated by tools/gen-costs.mjs from IkaEasy js/helper/db/buildings.js (in-game Help scrape, github.com/RandGor/IkaEasy).\n' +
  'export const COSTS=' + JSON.stringify(out) + ';\n');
